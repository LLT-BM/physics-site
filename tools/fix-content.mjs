let changed = 0; const missed = [];
for (const [file, rules] of Object.entries(RULES)) {
  const p = join(M, file);
  if (!existsSync(p)) { missed.push(file + ': файл не найден'); continue; }
  const orig = readFileSync(p, 'utf8');
  let s = orig; const marks = [];
  for (const r of rules) {
    if (r.done && s.includes(r.done)) { marks.push('='); continue; }
    const re = r.find instanceof RegExp ? r.find : rx(r.find);
    if (re.test(s)) {
      re.lastIndex = 0;
      s = s.replace(re, r.repl);
      marks.push('✓');
    } else {
      marks.push('✗');
      missed.push(file + ' → ' + context(orig, r.key));
    }
  }
  if (s !== orig) { changed++; if (!dry) writeFileSync(p, s, 'utf8'); }
  console.log((s !== orig ? (dry ? '[dry] ' : '[fix] ') : '[ok ] ') + file + '  ' + marks.join(' '));
}

