/* Контекст при промахе: показываем реальную строку из файла */
function context(text, key) {
  const i = text.indexOf(key);
  if (i < 0) return 'ключ «' + key + '» в файле не встречается';
  const from = text.lastIndexOf('\n', i) + 1;
  let to = text.indexOf('\n', i); if (to < 0) to = text.length;
  const line = text.slice(from, to).trim();
  return 'строка ' + (text.slice(0, i).split('\n').length) + ': ' +
         (line.length > 220 ? line.slice(0, 220) + '…' : line);
}

