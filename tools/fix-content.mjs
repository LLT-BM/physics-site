/* Гибкий RegExp из строки: пробелы, тире, кавычки, ё/е, запятая/точка, ·/× */
function rx(s, flags = 'g') {
  let out = s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  out = out.replace(/\s+/g, '[\\s\\u00A0\\u202F]+');
  out = out.replace(/[-–—−]/g, '[-–—−]');
  out = out.replace(/[«»„“"']/g, '[«»„“"\']');
  out = out.replace(/[её]/g, '[её]');
  out = out.replace(/,/g, '[.,]');
  out = out.replace(/[·⋅×]/g, '[·⋅×*]');
  return new RegExp(out, flags);
}

