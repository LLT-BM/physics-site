const norm = s => s.toLowerCase().replace(/\s+/g,' ').replace(/[ё]/g,'е').trim();
const q = s => '"' + String(s).replace(/\\/g,'\\\\').replace(/"/g,'\\"') + '"';

function questionsOf(body){
  const m = body.match(/##\s*Вопросы для самопроверки([\s\S]*?)(?=\n##\s|$)/);
  if(!m) return [];
  return m[1].split(/\r?\n/)
    .filter(l => /^\s*[-*]\s+/.test(l))
    .map(l => l.replace(/^\s*[-*]\s+/,'').trim())
    .filter(Boolean);
}

let changed = 0, unmatched = [];
for(const f of readdirSync(DIR).filter(x => x.endsWith('.md'))){
  const slug = f.replace(/\.md$/,'');
  const p = join(DIR,f);
  const orig = readFileSync(p,'utf8');
  const mm = orig.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if(!mm){ console.log('[?] '+f+' — нет frontmatter'); continue; }
  const eol = orig.includes('\r\n') ? '\r\n' : '\n';
  const fm = mm[1], body = orig.slice(mm[0].length);

  const kept = fm.split(/\r?\n/).filter(l => {
    const k = (l.match(/^([A-Za-z][A-Za-z0-9_]*)\s*:/) || [])[1];
    return !k || !['answers','checkpoints'].includes(k);
  });

  const qs = questionsOf(body);
  const table = (A[slug] || []).filter(([,a]) => a);
  const pairs = [];
  for(const question of qs){
    const nq = norm(question);
    const hit = table.find(([k]) => nq.includes(norm(k)));
    if(hit) pairs.push({ q: question, a: hit[1] });
    else unmatched.push(slug + ': ' + question.slice(0,70));
  }
  const cps = C[slug] || [];

  const lines = [];
  if(pairs.length){
    lines.push('answers:');
    for(const it of pairs) lines.push('  - q: ' + q(it.q), '    a: ' + q(it.a));
  }
  if(cps.length){
    lines.push('checkpoints:');
    for(const [name,setup,expected] of cps)
      lines.push('  - name: ' + q(name), '    setup: ' + q(setup), '    expected: ' + q(expected));
  }
  const out = '---' + eol + kept.concat(lines).join(eol) + eol + '---' + eol + body;
  if(out !== orig){
    changed++;
    if(!dry) writeFileSync(p, out, 'utf8');
    console.log((dry?'[dry] ':'[fix] ')+f.padEnd(26)+' → ответов '+pairs.length+'/'+qs.length+', точек '+cps.length);
  } else console.log('[ok ] '+f);
}
console.log('\n'+(dry?'Будет изменено':'Изменено')+' файлов: '+changed);
if(unmatched.length){
  console.log('\nВопросы без ответа ('+unmatched.length+'):');
  unmatched.forEach(x => console.log('  '+x));
}